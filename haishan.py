# 建立 海山分局 所有里別的集合 (Set)
haishan_lis = {li for lis in HAISHAN_STATIONS.values() for li in lis}


def get_police_precinct(li_name: str) -> str:
    """
    輸入里別名稱（如："深丘" 或 "深丘里"），回傳對應的警察分局。
    """
    name = li_name.strip()
    if not name.endswith("里"):
        name += "里"

    if name in haishan_lis:
        return "新北市政府警察局海山分局"
    return "新北市政府警察局板橋分局"


